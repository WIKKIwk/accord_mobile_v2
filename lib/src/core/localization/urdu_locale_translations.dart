  static final List<MapEntry<String, String>> _interpolatedTranslations =
      sortedTemplates(byEnglish);

  static List<MapEntry<String, String>> sortedTemplates(
    Map<String, String> translations,
  ) {
    final weightedEntries = translations.entries
        .where((entry) => entry.key.contains(r'$'))
        .map((entry) => MapEntry(_templateSpecificity(entry.key), entry))
        .where((entry) => entry.key > 0)
        .toList()
      ..sort((left, right) => right.key.compareTo(left.key));
    return List<MapEntry<String, String>>.unmodifiable(
      weightedEntries.map((entry) => entry.value),
    );
  }

  static int _templateSpecificity(String template) {
    var literalText = template;
    for (final token in _interpolationTokens(template)) {
      literalText = literalText.replaceFirst(token, '');
    }
    return RegExp(r'[A-Za-z\u00C0-\u024F\u0600-\u06FF]')
        .allMatches(literalText)
        .length;
  }

  static String text(String english) {
    return textFrom(english, byEnglish, _interpolatedTranslations) ?? english;
  }

  static String? textFrom(
    String source,
    Map<String, String> translations, [
    List<MapEntry<String, String>>? interpolatedTranslations,
  ]) {
    final exact = translations[source];
    if (exact != null) return exact;

    final templates = interpolatedTranslations ??
        translations.entries
            .where((entry) => entry.key.contains(r'$'))
            .toList(growable: false);

    for (final entry in templates) {
      final tokens = _interpolationTokens(entry.key);
      if (tokens.isEmpty) continue;
      final expression = StringBuffer('^');
      var sourceOffset = 0;
      for (final token in tokens) {
        final tokenOffset = entry.key.indexOf(token, sourceOffset);
        expression.write(
            RegExp.escape(entry.key.substring(sourceOffset, tokenOffset)));
        expression.write('(.*?)');
        sourceOffset = tokenOffset + token.length;
      }
      expression
        ..write(RegExp.escape(entry.key.substring(sourceOffset)))
        ..write(r'$');
      final match =
          RegExp(expression.toString(), dotAll: true).firstMatch(source);
      if (match == null) continue;

      final translated = StringBuffer();
      var translationOffset = 0;
      for (var index = 0; index < tokens.length; index++) {
        final tokenOffset =
            entry.value.indexOf(tokens[index], translationOffset);
        if (tokenOffset < 0) break;
        translated.write(entry.value.substring(translationOffset, tokenOffset));
        translated.write(match.group(index + 1) ?? '');
        translationOffset = tokenOffset + tokens[index].length;
      }
      translated.write(entry.value.substring(translationOffset));
      return translated.toString();
    }
    return null;
  }

  static List<String> _interpolationTokens(String template) {
    final tokens = <String>[];
    var index = 0;
    while (index < template.length) {
      if (template[index] != r'$' || index + 1 >= template.length) {
        index++;
        continue;
      }
      final start = index;
      if (template[index + 1] == '{') {
        var depth = 1;
        index += 2;
        while (index < template.length && depth > 0) {
          if (template[index] == '{') depth++;
          if (template[index] == '}') depth--;
          index++;
        }
        if (depth == 0) tokens.add(template.substring(start, index));
        continue;
      }
      index++;
      final first = template.codeUnitAt(index);
      if (!_isIdentifierStart(first)) continue;
      index++;
      while (index < template.length &&
          _isIdentifierPart(template.codeUnitAt(index))) {
        index++;
      }
      tokens.add(template.substring(start, index));
    }
    return tokens;
  }

  static bool _isIdentifierStart(int codeUnit) =>
      (codeUnit >= 65 && codeUnit <= 90) ||
      (codeUnit >= 97 && codeUnit <= 122) ||
      codeUnit == 95;

  static bool _isIdentifierPart(int codeUnit) =>
      _isIdentifierStart(codeUnit) || (codeUnit >= 48 && codeUnit <= 57);
